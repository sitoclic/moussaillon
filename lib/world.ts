/** Largeur et hauteur de référence : 2 unités par degré. */
export const WORLD_W = 720;
export const WORLD_H = 360;

export function project(lon: number, lat: number): [number, number] {
  return [Math.round((lon + 180) * 2 * 10) / 10, Math.round((90 - lat) * 2 * 10) / 10];
}

export function polyPath(poly: Poly): string {
  return poly.map(([lon, lat], i) => `${i ? "L" : "M"}${project(lon, lat).join(" ")}`).join(" ") + " Z";
}

/** Distance orthodromique approximative en milles nautiques entre deux points. */
export function distanceNm(a: [number, number], b: [number, number]) {
  const rad = Math.PI / 180;
  const [lon1, lat1] = [a[0] * rad, a[1] * rad];
  const [lon2, lat2] = [b[0] * rad, b[1] * rad];
  const d = Math.acos(
    Math.min(1, Math.sin(lat1) * Math.sin(lat2) + Math.cos(lat1) * Math.cos(lat2) * Math.cos(lon2 - lon1)),
  );
  return (d * 180 * 60) / Math.PI;
}

/** Formate une coordonnée en degrés et minutes : 46°30′ N. */
export function formatCoord(value: number, pos: string, neg: string) {
  const abs = Math.abs(value);
  const deg = Math.floor(abs);
  const min = Math.round((abs - deg) * 60);
  const [d, m] = min === 60 ? [deg + 1, 0] : [deg, min];
  return `${d}°${String(m).padStart(2, "0")}′ ${value >= 0 ? pos : neg}`;
}
